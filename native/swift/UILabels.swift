/// Native names for the 13 upstream language tables.
func languageDisplayName(_ code: String) -> String {
    switch code {
    case "cn": return "简体中文"
    case "tw": return "繁體中文"
    case "en": return "English"
    case "de": return "Deutsch"
    case "es": return "Español"
    case "fr": return "Français"
    case "it": return "Italiano"
    case "ko": return "한국어"
    case "pt": return "Português"
    case "ru": return "Русский"
    case "tr": return "Türkçe"
    case "ua": return "Українська"
    case "vi": return "Tiếng Việt"
    default: return code.uppercased()
    }
}

/// Returns true when the active UI language is Simplified Chinese.
func uiIsChinese() -> Bool {
    ARDMLocalization.shared().currentLanguage == "cn"
}
